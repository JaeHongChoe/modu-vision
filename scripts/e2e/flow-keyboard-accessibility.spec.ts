import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {test,expect} from './fixtures/test';
import {installDesktopHostShim} from './fixtures/desktop-host-shim';
const harness=require('./fixtures/harness.cjs');
test.use({actionTimeout:12000});
const sha=(file:string)=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

for(const theme of ['dark','light'])test(`owned graph keyboard movement, grouped undo and focus navigation (${theme})`,async({page,request,renderer,workspace,evidence})=>{
  test.setTimeout(150000);
  await installDesktopHostShim(page,renderer.port);
  const api=async(route:string,body?:unknown)=>{const response=body===undefined?await request.get(renderer.origin+route):route.endsWith('/update')?await request.put(renderer.origin+route,{data:body}):await request.post(renderer.origin+route,{data:body});expect(response.ok(),await response.text()).toBe(true);return response.json();};
  const script=path.join(harness.REPO_ROOT,'scripts/e2e/fixtures/flow_navigation_control.py');
  const input=JSON.parse(execFileSync(harness.resolvePython(),[script,workspace.root],{encoding:'utf8',timeout:15000}));
  await api('/api/project/create',{name:'Owned keyboard flow',task:'classification'});
  await api('/api/project/update',{source_dataset_dir:input.source});
  const project=await api('/api/project/current');
  await api('/api/dataset/import',{folder_path:input.source,task:'classification'});
  const seeded=JSON.parse(execFileSync(harness.resolvePython(),[script,workspace.root,JSON.stringify(project)],{encoding:'utf8',timeout:15000}));
  await page.goto(renderer.url);
  await expect(page.getByTitle('프로젝트 관리',{exact:true})).toContainText(project.name);
  await page.getByRole('navigation',{name:'Workflow Stages'}).getByRole('button').nth(4).click();
  const advanced=page.getByRole('button',{name:'고급 편집',exact:true});if(await advanced.count())await advanced.click();
  await page.getByRole('tab',{name:'편집',exact:true}).click();
  await expect(page.locator('[data-flow-node-id]')).toHaveCount(seeded.graph.nodes.length);
  await page.evaluate(theme=>document.documentElement.dataset.theme=theme,theme);
  if(theme==='light')await page.setViewportSize({width:980,height:820});
  const search=page.getByLabel('플로우 노드 검색',{exact:true});
  if(!await search.isVisible())await page.getByText('노드 찾기·전체 보기',{exact:true}).click();
  await search.fill('먼곳 판정');
  await page.getByRole('list',{name:'노드 검색 결과'}).getByRole('button').press('Enter');
  const node=page.locator(`[data-flow-node-id="${seeded.target_id}"]`),frame=node.locator('[data-flow-node-focus]');
  await expect(frame).toBeFocused();
  const position=()=>node.evaluate(element=>({x:parseFloat((element as HTMLElement).style.left),y:parseFloat((element as HTMLElement).style.top)}));
  const before=await position();
  await page.keyboard.down('ArrowRight');await page.keyboard.down('ArrowRight');await page.keyboard.down('ArrowRight');await page.keyboard.up('ArrowRight');
  await expect.poll(position).toEqual({...before,x:before.x+30});
  await page.getByRole('button',{name:'플로우 실행 취소',exact:true}).click();
  await expect.poll(position).toEqual(before);
  await frame.focus();await frame.press('Shift+ArrowDown');
  await expect.poll(position).toEqual({...before,y:before.y+50});
  await page.getByRole('button',{name:'플로우 실행 취소',exact:true}).click();await expect.poll(position).toEqual(before);
  const canvas=page.getByLabel('플로우 그래프 캔버스',{exact:true});
  await canvas.evaluate(element=>{element.scrollTop=0;element.scrollLeft=0;});
  await frame.focus();
  await expect.poll(()=>canvas.evaluate(element=>element.scrollLeft)).toBeGreaterThan(100);
  await frame.press('Escape');await expect(frame).toHaveAttribute('aria-label',/선택 안됨/);
  await page.getByText('빠른 노드 추가·연결·실행 자원',{exact:true}).click();
  const source=page.locator('[data-flow-node-id]').first();
  await source.locator('[data-flow-node-focus]').focus();
  const port=source.getByRole('button',{name:/Start connection/}).first();await port.click();
  await expect(page.getByRole('button',{name:/연결 시작:.*취소/})).toBeVisible();
  await port.press('Escape');
  await expect(page.getByRole('button',{name:/연결 시작:.*취소/})).toHaveCount(0);
  await expect(page.locator('#flow-keyboard-help')).toContainText('Shift+방향키');
  await evidence.screenshot(page,`keyboard-flow-${theme}`);
  expect(sha(seeded.graph_file)).toBe(seeded.graph_sha256);
  for(const row of input.files)expect(sha(row.path)).toBe(row.sha256);
  evidence.note('keyboard',{theme,position:before,grouped_undo:true,search_focus:true,escape_connection:true,source_unchanged:true,saved_graph_unchanged:true,model_execution:false});
});
