/** Durable wire DTOs shared with the actor-scoped assistant task ledger. */
export type TaskStatus = 'draft' | 'ready' | 'running' | 'waiting_human' | 'waiting_job' | 'paused' | 'needs_reconciliation' | 'failed' | 'completed';
export type StepStatus = 'pending' | 'running' | 'waiting_human' | 'waiting_job' | 'completed' | 'failed' | 'uncertain';
export type ActionId = 'create_project' | 'import_dataset' | 'save_split' | 'configure_training' | 'configure_input_recipe' | 'generate_label_drafts' | 'start_training' | 'evaluate_model' | 'save_flow' | 'evaluate_flow' | 'inspect_test' | 'export_report' | 'open_step';
export interface TaskPlanInput {
  goal: string;
  /** Generated by the local controller, never taken from provider arguments. */
  binding: string;
  steps: Array<{ action: ActionId; args: Record<string, unknown>; label: string }>;
}
export const EXECUTION_POLICY_VERSION = 'continuous-execution-v1';
export interface TaskExecutionRequest {source: 'user_request' | 'oneclick';signal?:AbortSignal}
export interface TaskAuthorization {
  source:TaskExecutionRequest['source'];
  scope: {workspace_id: string; actor_id: string};
  plan_sha256: string;
  binding: string;
  policy_version: typeof EXECUTION_POLICY_VERSION;
  authorized_at: string;
  allowed_steps: string[];
}
export interface TaskStep {
  id: string;
  action: ActionId;
  args: Record<string, unknown>;
  label: string;
  status: StepStatus;
  attempt_id: string | null;
  receipt: Record<string, unknown> | null;
  error: string | null;
}
export interface TaskQualityAssessment {
  assessment_id:string;
  evaluation_id:string;
  status:'qualified'|'not_qualified'|'input_needed';
  decision_source:'policy';
  reasons:string[];
  subject_kind?:'model'|'flow';
  quality_qualified?:boolean;
}
export function hasPendingTaskQuality(task:AssistantTask|null):boolean{
  return Boolean(task?.authorization&&task.steps.some(step=>step.status==='completed'&&['evaluate_model','evaluate_flow'].includes(step.action)
    &&typeof step.receipt?.evaluation_id==='string'&&(!step.receipt.quality_assessment
      ||(step.receipt.quality_assessment as {status?:unknown}).status==='pending')));
}
export interface AssistantTask {
  schema_version: 1;
  id: string;
  revision: number;
  status: TaskStatus;
  goal: string;
  plan_sha256: string;
  binding: string;
  steps: TaskStep[];
  approval: { plan_sha256: string; binding: string; confirmed_at: string } | null;
  /** App-owned execution intent, kept separate from a person's review record. */
  authorization?: TaskAuthorization | null;
  current_step_id: string | null;
  message: string | null;
  created_at: string;
  updated_at: string;
}
export interface TaskEvent {
  expected_revision: number;
  binding: string;
  type: 'approve' | 'authorize' | 'recheck' | 'quality_result' | 'begin_step' | 'complete_step' | 'wait_step' | 'pause' | 'resume' | 'fail_step' | 'reconcile_step' | 'record_evidence';
  assessment_id?:string;
  authorization_source?: TaskExecutionRequest['source'];
  step_id?: string;
  attempt_id?: string;
  receipt?: Record<string, unknown>;
  message?: string;
  binding_after?: string;
  wait_kind?: 'human' | 'job';
  confirmed?: boolean;
}
export interface TaskActionResult {
  kind: 'completed' | 'waiting_human' | 'waiting_job' | 'needs_reconciliation';
  receipt?: Record<string, unknown>;
  message?: string;
  reasonCode?: 'waiting_input' | 'waiting_resource' | 'waiting_job' | 'failed' | 'needs_reconciliation';
  /** Only an adapter-verified transition may advance the local authority fence. */
  bindingAfter?: string;
}
export interface TaskControl {
  /** Local-only model identity from the latest completed upstream training/evaluation receipt. */
  priorModelJobId?: string;
  isCurrent(): boolean;
  isPaused(): boolean;
  /** Fixed provider/session authority, supplied locally around permitted action-owned state transitions. */
  isAuthorityCurrent?(): boolean;
  /** Bounded same-attempt evidence checkpoint, never an application action. */
  checkpoint?(receipt: Record<string, unknown>): Promise<void>;
}
